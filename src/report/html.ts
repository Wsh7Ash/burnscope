export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const STATE_COLOURS: Readonly<Record<BudgetState, { fg: string; bg: string }>> = {
  healthy: { fg: '#0b5c2e', bg: '#e3f5ea' },
  'at-risk': { fg: '#7a4700', bg: '#fdf0d5' },
  burning: { fg: '#8c2f00', bg: '#fde5d6' },
  exhausted: { fg: '#7a1414', bg: '#fbdcdc' },
};

const CHART = {
  width: 900,
  height: 300,
  margin: { top: 18, right: 18, bottom: 38, left: 58 },
  yMin: 1e-3,
  yMax: 1e2,
  maxPoints: 1200,
} as const;

/**
 * Self-contained HTML report: no external stylesheets, scripts or fonts, so it
 * can be committed to a repository or attached to a CI artifact and still
 * render offline.
 */
export function renderHtml(analysis: Analysis): string {
  const parts: string[] = [];
  parts.push('<!doctype html>');
  parts.push('<html lang="en">');
  parts.push('<head>');
  parts.push('<meta charset="utf-8">');
  parts.push('<meta name="viewport" content="width=device-width, initial-scale=1">');
  parts.push(`<title>Burnscope report ${escapeHtml(formatDate(analysis.asOf))}</title>`);
  parts.push(`<style>${STYLE}</style>`);
  parts.push('</head>');
  parts.push('<body>');
  parts.push('<header class="page">');
  parts.push('<h1>Burnscope report</h1>');
  parts.push(
    `<p class="meta">Analyzed at <strong>${escapeHtml(formatTimestamp(analysis.asOf))}</strong> · ` +
      `alert profile <strong>${escapeHtml(analysis.profile.name)}</strong> ` +
      `<code>${escapeHtml(analysis.profile.id)}</code> · minimum window coverage ` +
      `${escapeHtml(formatPercent(analysis.minCoverage, 0))}</p>`,
  );
  parts.push('</header>');
  parts.push('<main class="page">');
  parts.push(summaryTable(analysis));

  for (const slo of analysis.slos) {
    parts.push(sloCard(slo));
  }

  if (analysis.dataQuality.length > 0) {
    parts.push('<section class="card"><h2>Input data quality</h2><ul class="notes">');
    const seen = new Set<string>();
    for (const note of analysis.dataQuality) {
      const text = `${note.scope}: ${note.message}`;
      if (seen.has(text)) continue;
      seen.add(text);
      parts.push(`<li>${escapeHtml(text)}</li>`);
    }
    parts.push('</ul></section>');
  }

  parts.push('</main>');
  parts.push(`<footer class="page"><p>Generated by burnscope ${escapeHtml(VERSION)}. No network requests were made.</p></footer>`);
  parts.push('</body>');
  parts.push('</html>');
  return `${parts.join('\n')}\n`;
}

function summaryTable(analysis: Analysis): string {
  const rows = analysis.slos
    .map((slo) => {
      const state = STATE_COLOURS[slo.budget.state];
      return (
        '<tr>' +
        `<td><a href="#${escapeHtml(anchor(slo.spec.name))}"><code>${escapeHtml(slo.spec.name)}</code></a></td>` +
        `<td>${escapeHtml(formatPercent(slo.spec.objective, 2))}</td>` +
        `<td>${escapeHtml(slo.period.sufficient ? formatBurn(slo.period.burnRate) : 'n/a')}</td>` +
        `<td>${escapeHtml(formatPercent(slo.budget.consumed))}</td>` +
        `<td>${escapeHtml(formatPercent(slo.budget.remaining))}</td>` +
        `<td><span class="badge" style="color:${state.fg};background:${state.bg}">` +
        `${escapeHtml(budgetStateLabel(slo.budget.state))}</span></td>` +
        `<td>${slo.firing.length} of ${slo.alerts.length}</td>` +
        '</tr>'
      );
    })
    .join('\n');

  return (
    '<section class="card"><h2>Summary</h2><table><thead><tr>' +
    '<th>SLO</th><th>Objective</th><th>Burn rate</th><th>Budget used</th><th>Remaining</th><th>State</th><th>Rules firing</th>' +
    `</tr></thead><tbody>\n${rows}\n</tbody></table></section>`
  );
}

function sloCard(slo: SloResult): string {
  const budget = slo.budget;
  const state = STATE_COLOURS[budget.state];
  const parts: string[] = [];

  parts.push(`<section class="card" id="${escapeHtml(anchor(slo.spec.name))}">`);
  parts.push(
    `<h2><code>${escapeHtml(slo.spec.name)}</code> ` +
      `<span class="badge" style="color:${state.fg};background:${state.bg}">${escapeHtml(budgetStateLabel(budget.state))}</span></h2>`,
  );
  if (slo.spec.description !== undefined) {
    parts.push(`<p class="desc">${escapeHtml(slo.spec.description)}</p>`);
  }

  parts.push('<dl class="grid">');
  parts.push(stat('Objective', formatPercent(slo.spec.objective, 2)));
  parts.push(stat('Error budget', formatErrorRate(budget.budgetRatio)));
  parts.push(
    stat(
      'Error rate',
      slo.period.sufficient ? formatErrorRate(slo.period.errorRate) : `n/a — ${slo.period.note}`,
    ),
  );
  parts.push(stat('Burn rate', slo.period.sufficient ? `${formatBurn(slo.period.burnRate)} (1x is sustainable)` : 'n/a'));
  parts.push(
    stat(
      'Window elapsed',
      `${formatDuration(budget.elapsedSeconds)} of ${formatDuration(budget.periodSeconds)} (${formatPercent(budget.elapsedFraction)})`,
    ),
  );
  parts.push(
    stat(
      'Runway',
      budget.neverExhausts
        ? 'budget cannot be exhausted'
        : budget.exhaustsInSeconds === 0
          ? 'already exhausted'
          : formatDuration(budget.exhaustsInSeconds),
    ),
  );
  parts.push(stat('Exhaustion', budget.neverExhausts ? 'never at this rate' : formatTimestamp(budget.exhaustsAt)));
  parts.push(stat('Series matched', `${slo.goodSeriesCount} good, ${slo.badSeriesCount} bad`));
  parts.push('</dl>');

  parts.push(budgetBar(budget.remaining, budget.consumed));

  parts.push(burnChart(slo));

  parts.push('<h3>Multi-window multi-burn-rate alerts</h3>');
  parts.push('<table class="alerts"><thead><tr><th>Rule</th><th>Severity</th><th>Long</th><th>Short</th><th>Threshold</th><th>Long burn</th><th>Short burn</th><th>Status</th></tr></thead><tbody>');
  for (const alert of slo.alerts) {
    const status = alert.firing ? 'FIRING' : alert.evaluated ? 'clear' : 'not evaluated';
    const cls = alert.firing ? ' class="firing"' : '';
    parts.push(
      `<tr${cls}><td><code>${escapeHtml(alert.rule.id)}</code></td>` +
        `<td>${escapeHtml(alert.rule.severity)}</td>` +
        `<td>${escapeHtml(formatWindow(alert.rule.longWindowSeconds))}</td>` +
        `<td>${escapeHtml(formatWindow(alert.rule.shortWindowSeconds))}</td>` +
        `<td>${escapeHtml(`${alert.rule.burnRate}x`)}</td>` +
        `<td>${escapeHtml(formatBurn(alert.long.burnRate))}</td>` +
        `<td>${escapeHtml(formatBurn(alert.short.burnRate))}</td>` +
        `<td>${escapeHtml(status)}</td></tr>`,
    );
  }
  parts.push('</tbody></table>');
  for (const alert of slo.firing) {
    parts.push(`<p class="action">${escapeHtml(alert.rule.action)}</p>`);
  }

  parts.push('<h3>Observations</h3><ul class="notes">');
  for (const observation of slo.observations) parts.push(`<li>${escapeHtml(observation)}</li>`);
  parts.push('</ul>');

  const caveats = [...new Set([...slo.warnings, ...budget.notes])];
  if (caveats.length > 0) {
    parts.push('<h3>Caveats</h3><ul class="notes warn">');
    for (const caveat of caveats) parts.push(`<li>${escapeHtml(caveat)}</li>`);
    parts.push('</ul>');
  }

  parts.push('</section>');
  return parts.join('\n');
}

function stat(label: string, value: string): string {
  return `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`;
}

function budgetBar(remaining: number, consumed: number): string {
  const used = Math.max(0, Math.min(100, consumed * 100));
  const left = Math.max(0, Math.min(100, remaining * 100));
  const label = `Error budget: ${formatPercent(consumed)} used, ${formatPercent(remaining)} remaining`;
  return (
    `<div class="budget"><div class="budget-label">${escapeHtml(label)}</div>` +
    `<div class="budget-track" role="img" aria-label="${escapeHtml(label)}">` +
    `<div class="budget-used" style="width:${used.toFixed(2)}%"></div>` +
    `<div class="budget-left" style="width:${left.toFixed(2)}%"></div>` +
    '</div></div>'
  );
}

function burnChart(slo: SloResult): string {
  const points = decimate(slo.curve, CHART.maxPoints);
  if (points.length < 2) {
    return (
      '<figure class="chart"><figcaption>Burn rate over time (log scale)</figcaption>' +
      '<p class="desc">Not enough consecutive samples in both series to draw a burn-rate curve.</p></figure>'
    );
  }

  const { width, height, margin } = CHART;
  const plotLeft = margin.left;
  const plotTop = margin.top;
  const plotWidth = width - margin.left - margin.right;
  const plotHeight = height - margin.top - margin.bottom;

  const first = points[0];
  const last = points[points.length - 1];
  const tMin = first?.t ?? 0;
  const tMax = last?.t ?? 0;
  const span = Math.max(1, tMax - tMin);

  const yFor = (value: number): number => {
    const clamped = Math.min(CHART.yMax, Math.max(CHART.yMin, value > 0 ? value : CHART.yMin));
    const lo = Math.log10(CHART.yMin);
    const hi = Math.log10(CHART.yMax);
    const t = (Math.log10(clamped) - lo) / (hi - lo);
    return plotTop + plotHeight * (1 - t);
  };
  const xFor = (t: number): number => plotLeft + (plotWidth * (t - tMin)) / span;

  const decades = [1e-3, 1e-2, 1e-1, 1, 10, 100];
  const grid = decades
    .map((decade) => {
      const y = yFor(decade).toFixed(1);
      const emphasise = decade === 1;
      return (
        `<line x1="${plotLeft}" y1="${y}" x2="${plotLeft + plotWidth}" y2="${y}" ` +
        `stroke="${emphasise ? '#b3261e' : '#d8dde3'}" stroke-width="${emphasise ? 1.5 : 1}" ` +
        `${emphasise ? '' : 'stroke-dasharray="3 3" '}></line>` +
        `<text class="axis" x="${plotLeft - 8}" y="${(Number(y) + 4).toFixed(1)}" text-anchor="end">` +
        `${decade}x</text>`
      );
    })
    .join('');

  const overTop = yFor(CHART.yMax).toFixed(1);
  const sustainableY = yFor(1).toFixed(1);
  const path = points
    .map((point, index) => `${index === 0 ? 'M' : 'L'}${xFor(point.t).toFixed(1)} ${yFor(point.burnRate).toFixed(1)}`)
    .join(' ');

  const peak = points.reduce<IntervalRate | undefined>(
    (best, point) => (best === undefined || point.burnRate > best.burnRate ? point : best),
    undefined,
  );
  const caption =
    `Burn rate over time (log scale) — ${points.length} intervals, ` +
    `peak ${formatBurn(peak?.burnRate ?? 0)} at ${formatTimestamp(peak?.t ?? 0)}`;

  return (
    '<figure class="chart">' +
    `<figcaption>${escapeHtml(caption)}</figcaption>` +
    `<svg viewBox="0 0 ${width} ${height}" role="img" aria-label="${escapeHtml(caption)}" ` +
    `preserveAspectRatio="xMidYMid meet">` +
    `<rect x="${plotLeft}" y="${overTop}" width="${plotWidth}" height="${(Number(sustainableY) - Number(overTop)).toFixed(1)}" ` +
    'fill="#fbdcdc" fill-opacity="0.55"></rect>' +
    `<text class="zone" x="${plotLeft + plotWidth - 6}" y="${(Number(overTop) + 14).toFixed(1)}" text-anchor="end">` +
    'faster than sustainable</text>' +
    grid +
    `<path d="${path}" fill="none" stroke="#1a56a8" stroke-width="1.6" stroke-linejoin="round"></path>` +
    `<text class="axis" x="${plotLeft}" y="${height - 14}">${escapeHtml(formatDate(tMin))}</text>` +
    `<text class="axis" x="${plotLeft + plotWidth}" y="${height - 14}" text-anchor="end">${escapeHtml(formatDate(tMax))}</text>` +
    `<line x1="${plotLeft}" y1="${plotTop}" x2="${plotLeft}" y2="${plotTop + plotHeight}" stroke="#8b949e"></line>` +
    '<line x1="' + plotLeft + '" y1="' + (plotTop + plotHeight) + '" x2="' + (plotLeft + plotWidth) + '" y2="' + (plotTop + plotHeight) + '" stroke="#8b949e"></line>' +
    `</svg></figure>`
  );
}

/**
 * Reduce a curve to at most `maxPoints`, keeping the extremes of each bucket so
 * spikes survive downsampling.
 */
export function decimate(points: readonly IntervalRate[], maxPoints: number): IntervalRate[] {
  if (maxPoints < 4) throw new RangeError('maxPoints must be at least 4');
  if (points.length <= maxPoints) return [...points];

  const buckets = Math.floor(maxPoints / 2);
  const size = points.length / buckets;
  const out: IntervalRate[] = [];
  for (let b = 0; b < buckets; b += 1) {
    const start = Math.floor(b * size);
    const end = Math.min(points.length, Math.floor((b + 1) * size));
    if (end <= start) continue;
    let lo = points[start];
    let hi = points[start];
    for (let i = start + 1; i < end; i += 1) {
      const point = points[i];
      if (point === undefined) continue;
      if (point.burnRate < (lo?.burnRate ?? 0)) lo = point;
      if (point.burnRate > (hi?.burnRate ?? 0)) hi = point;
    }
    if (lo !== undefined && hi !== undefined) {
      if (lo.t <= hi.t) {
        if (out[out.length - 1] !== lo) out.push(lo);
        if (hi !== lo) out.push(hi);
      } else {
        if (out[out.length - 1] !== hi) out.push(hi);
        if (lo !== hi) out.push(lo);
      }
    }
  }
  return out;
}

